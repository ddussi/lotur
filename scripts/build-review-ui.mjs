import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const root = new URL("../", import.meta.url);
for (const [entry, filename, globalName, exportName] of [
  ["entry.ts", "review-bootstrap.generated.ts", "ReviewTunnelOverlay", "REVIEW_BOOTSTRAP_SOURCE"],
  ["control-entry.ts", "review-control.generated.ts", "ReviewTunnelUi", "REVIEW_CONTROL_SHARED_SOURCE"],
]) {
const target = new URL(`apps/gateway/src/${filename}`, root);
const result = await build({
  configFile: false,
  logLevel: "silent",
  build: {
    write: false,
    target: "es2022",
    minify: false,
    lib: {
      entry: fileURLToPath(new URL(`apps/gateway/src/review-ui/${entry}`, root)),
      formats: ["iife"],
      name: globalName,
    },
  },
});
const output = Array.isArray(result) ? result[0].output : result.output;
if (output.length !== 1 || output[0].type !== "chunk")
  throw new Error("Review UI must build into a single script");
const source = `// Generated by npm run build:review-ui; edit review-ui/*.ts instead.\n// biome-ignore lint/suspicious/noTemplateCurlyInString: serialized JavaScript bundle\nexport const ${exportName} = ${JSON.stringify(output[0].code)};\n`;
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== source)
    throw new Error("Review UI bundle is stale; run npm run build:review-ui");
} else await writeFile(target, source);

}
